def consumer_values(paths: dict, name: str, key: str, role: str) -> dict:
    values = values_at(paths)
    if role == "worker":
        values["workers"] = worker_with(tokenSecretName=name, tokenSecretKey=key)
    elif role == "gateway":
        values["gateway"] = {"auth": {"mode": "token", "tokenSecretName": name, "tokenSecretKey": key}}
    elif role == "gateway-extra-env":
        values["gateway"] = {
            "auth": {"mode": "token"},
            "extraEnv": [{"name": "SIE_AUTH_TOKEN", "valueFrom": {"secretKeyRef": {"name": name, "key": key}}}],
        }
    elif role == "upstream":
        values["upstreams"] = {"team": upstream(api_key_secret={"name": name, "key": key})}
    elif role == "mcp":
        values["mcpEdge"] = {"enabled": True, "clusterApiKey": {"existingSecretName": name, "secretKey": key}}
    else:
        raise AssertionError(role)
    return values


def consumed_refs(docs: list[dict]) -> set[tuple[str, str, str | None]]:
    """Structured consumers only; Secret creation alone is not consumption."""
    refs = set()
    for doc in docs:
        namespace = doc["metadata"].get("namespace", "sie")
        if doc["kind"] in {"Deployment", "StatefulSet"}:
            spec = doc["spec"]["template"]["spec"]
            for container in (spec.get("containers") or []) + (spec.get("initContainers") or []):
                for env in container.get("env", []) or []:
                    ref = env.get("valueFrom", {}).get("secretKeyRef")
                    if ref:
                        refs.add((namespace, ref["name"], ref["key"]))
            for volume in spec.get("volumes", []) or []:
                if ref := volume.get("secret"):
                    for item in ref.get("items", [{"key": None}]):
                        refs.add((namespace, ref["secretName"], item["key"]))
        elif doc["kind"] == "Job":
            for container in doc["spec"]["template"]["spec"].get("containers", []):
                args = container.get("args", [])
                if args and args[0] in {"create", "patch"}:
                    for arg in args:
                        if arg.startswith("--secret-name="):
                            refs.add((namespace, arg.split("=", 1)[1], "ca"))
        elif doc["kind"] == "Issuer" and (ref := doc["spec"].get("ca")):
            refs.update((namespace, ref["secretName"], key) for key in ("tls.crt", "tls.key"))
        elif doc["kind"] == "ServiceMonitor":
            for endpoint in doc["spec"]["endpoints"]:
                ref = endpoint.get("tlsConfig", {}).get("ca", {}).get("secret")
                if ref:
                    refs.add((namespace, ref["name"], ref["key"]))
    return refs


@pytest.mark.parametrize(("case", "paths", "name", "key"), CASES, ids=[case[0] for case in CASES])
def test_dependency_fixture_has_the_actual_consumer(
    tmp_path: Path, case: str, paths: dict, name: str, key: str
) -> None:
    values = values_at(paths)
    namespace = values.get("global", {}).get("namespace", "sie")
    refs = consumed_refs(rendered_documents(tmp_path, values))
    assert (namespace, name, key) in refs or (namespace, name, None) in refs, (case, refs)


@pytest.mark.parametrize("role", ["worker", "gateway", "gateway-extra-env", "upstream", "mcp"])
@pytest.mark.parametrize(("case", "paths", "name", "key"), CASES, ids=[case[0] for case in CASES])
def test_dependency_key_cannot_be_a_sie_credential(
    tmp_path: Path, role: str, case: str, paths: dict, name: str, key: str
) -> None:
    result = render_chart(tmp_path, consumer_values(paths, name, key, role))
    assert result.returncode != 0, case
    assert "same Secret key" in result.stderr, result.stderr
    assert f"{name}/{key}" in result.stderr, result.stderr


@pytest.mark.parametrize(("case", "paths", "name", "key"), CASES, ids=[case[0] for case in CASES])
def test_another_key_in_the_same_secret_remains_allowed(
    tmp_path: Path, case: str, paths: dict, name: str, key: str
) -> None:
    result = render_chart(tmp_path, consumer_values(paths, name, "separate-sie-token", "worker"))
    assert result.returncode == 0, (case, result.stderr)


